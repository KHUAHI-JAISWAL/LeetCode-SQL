# Definition for a binary tree node.
# class TreeNode:
#     def __init__(self, val=0, left=None, right=None):
#         self.val = val
#         self.left = left
#         self.right = right
class Solution:
    def deleteNode(self, root: TreeNode | None, key: int) -> TreeNode | None:


        #Brute Force: Node ko search karke tree rebuild karo — Time: O(N), Space: O(N).

        #Best Approach: BST property use karke node delete karo; 0 ya 1 child ho to child return karo, 2 children hon to inorder successor se replace karo — Time: O(H), Space: O(H) recursion stack.


        if not root:
            return None

        if key < root.val:
            root.left = self.deleteNode(root.left, key)
        elif key > root.val:
            root.right = self.deleteNode(root.right, key)
        else:
            if not root.left:
                return root.right
            if not root.right:
                return root.left

            successor = root.right
            while successor.left:
                successor = successor.left

            root.val = successor.val
            root.right = self.deleteNode(root.right, successor.val)

        return root

    
        